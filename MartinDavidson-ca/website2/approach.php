 <h2>Therapy That Fits&nbsp;<em>You</em></h2>
 <p>Research—and fifteen years in the chair—tell me the single best predictor of
  change is the bond between therapist and client. So our first order of
  business is to build trust: a space where every thought or feeling can be
  voiced without judgment and met with warmth, respect, and the occasional
  well-timed laugh.</p>

 <h2>The Work in Three Phases</h2>
 <p><strong>1.&nbsp;Lay the Foundation&nbsp;&mdash;</strong> We talk about what brings you in, sketch out goals,
  and agree on a pace that feels manageable.</p>
 <p><strong>2.&nbsp;Shine a Light on Patterns&nbsp;&mdash;</strong> Together we notice habits of thinking,
  feeling, and relating that once protected you but now keep distress
  alive.</p>
 <p><strong>3.&nbsp;Try New Ways Forward&nbsp;&mdash;</strong> Using tailored techniques—CBT skills,
  emotion-focused exercises, family-systems work, or playful activities for
  younger clients—we experiment until life outside the office starts to feel
  lighter.</p>

 <h2>Guiding Principles You’ll Notice</h2>
 <ul>
  <li><strong>Collaboration, always.</strong> Your voice steers the ship; I adapt methods
   to you.</li>
  <li><strong>Comfortable pace.</strong> We move only as quickly as feels right.</li>
  <li><strong>Strength-focused.</strong> We’ll highlight the resilience already in you
   (and your family).</li>
  <li><strong>Humour &amp; humanity.</strong> Serious work balances with ease, curiosity,
   and the odd grin.</li>
 </ul>

 <h2>Techniques in the Toolkit</h2>
 <p>Cognitive-behavioural, emotion-focused, family-systems, and play therapy
  are mixed and matched to suit you&mdash;your personality dictates the
  recipe.</p>

 <h2>Working with Parents &amp; Families</h2>
 <p>When children or adolescents are involved, therapy is a team sport. I meet
  one-on-one with the young person <em>and</em> coach parents so everyone
  understands what’s happening beneath the surface and can pull in the same
  direction.</p>

