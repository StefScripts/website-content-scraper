 <h2>About&nbsp;Martin</h2>

 <p>I completed my doctoral degree in Clinical Psychology at Simon Fraser
  University with a child‑clinical specialization. For the past fifteen
  years I’ve delivered community‑based mental‑health services to children,
  adolescents, and families—experience that taught me how young people want
  to be treated and how to build the therapeutic relationships essential for
  success.</p>

 <p>My clinical work has included positions at the Maples Adolescent Treatment
  Centre and with Child and Youth Mental Health in Delta, where I provided
  assessment and treatment for youth facing severe emotional distress and
  behavioural challenges—from conduct problems and delinquency to depression
  and self‑harm. During my doctoral training I also conducted research on
  how adolescents themselves view mental‑health services, focusing on the
  therapist qualities and relationship factors that help young people engage
  and thrive.</p>

 <p>Alongside private practice, I currently teach undergraduate courses at
  Simon Fraser University, including Adolescent Development and Developmental
  Psychopathology.</p>

