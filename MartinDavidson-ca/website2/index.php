 <!-- How Therapy Feels Here -->
 <h2>How Therapy Feels Here</h2>
 <p>My style is collaborative and flexible. Rather than fitting you into a
  preset program, I draw from cognitive‑behavioural, emotion‑focused,
  family‑systems, and play‑therapy techniques to build a plan that matches
  your personality and pace. With younger clients, parents are active
  partners: you’ll gain insight into what your child is experiencing and
  concrete ways to support them, so everyone is working from the same
  playbook and attachment bonds grow stronger.</p>

 <!-- What to Expect -->
 <h2>What to Expect in Our Work Together</h2>
 <p>Think of the first few sessions as laying a foundation: we build trust, set
